def verify():
    worst, worst_at, n, bad = 0.0, None, 0, []
    for (k, nom), row in sorted(TABLE_10C.items()):
        f = midband(k)
        for rh, published in sorted(row.items()):
            got = alpha_db_per_km(f, 10.0, rh)
            rel = abs(got - published) / published
            n += 1
            if rel > worst:
                worst, worst_at = rel, (nom, rh, published, got)
            if rel > 0.005:
                bad.append((nom, rh, published, got, rel))
    print("%d published values, worst relative error %.3f%%" % (n, 100 * worst))
    print("   at %d Hz, %d%% RH: published %.4g, computed %.4g" % worst_at)
    for b in bad:
        print("   OUTLIER %d Hz %d%% published %.4g computed %.4g (%.1f%%)"
              % (b[0], b[1], b[2], b[3], 100 * b[4]))
    if bad:
        raise SystemExit("transcription or equations disagree beyond table precision")
    return n


def emit(path):
    out = [HEADER]
    for (k, nom), row in sorted(TABLE_10C.items()):
        for rh, v in sorted(row.items()):
            out.append("    {%4d, %9.1f, %6.1f, %6.1f, %12.6g},\n" % (k, nom, 10.0, rh, v))
    out.append(FOOTER)
    pathlib.Path(path).write_text("".join(out))


if __name__ == "__main__":
    n = verify()
    dst = sys.argv[1] if len(sys.argv) > 1 else "tests/data/iso9613_table.hpp"
    emit(dst)
    print("wrote %d entries -> %s" % (n, dst))
