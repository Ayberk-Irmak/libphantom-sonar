"""Generate tests/data/iso9613_table.hpp, and check it against the equations.

Values transcribed from ISO 9613-1:1993 Table 1 (a)(g)(h) -- the published
pure-tone atmospheric-absorption attenuation coefficients in dB/km at one
standard atmosphere. The PDF's text layer is OCR-damaged in places ("lO" for
"10", stray characters), so only cells that could be read unambiguously are
included; a corrupted cell would show up here as a large outlier rather than
silently weakening the test.

The equations below are entered SEPARATELY, from the standard's clauses 6.2 and
annex B, so agreement between them and the table is evidence about both.

    python3 tools/make_iso9613_table.py [output.hpp]
"""
import math
import pathlib
import sys

PR, T0, T01 = 101.325, 293.15, 273.16


def alpha_db_per_km(f_hz, temp_c, rh, p_kpa=PR):
    T = temp_c + 273.15
    psat_over_pr = 10.0 ** (-6.8346 * (T01 / T) ** 1.261 + 4.6151)
    h = rh * psat_over_pr * PR / p_kpa
    pa_pr = p_kpa / PR
    frO = pa_pr * (24.0 + 4.04e4 * h * (0.02 + h) / (0.391 + h))
    frN = pa_pr * (T / T0) ** -0.5 * (
        9.0 + 280.0 * h * math.exp(-4.170 * ((T / T0) ** (-1.0 / 3.0) - 1.0)))
    f2 = f_hz * f_hz
    classical = 1.84e-11 * (1.0 / pa_pr) * (T / T0) ** 0.5
    relax = (T / T0) ** -2.5 * (
        0.01275 * math.exp(-2239.1 / T) / (frO + f2 / frO)
        + 0.1068 * math.exp(-3352.0 / T) / (frN + f2 / frN))
    return 8.686 * f2 * (classical + relax) * 1000.0


def midband(k):
    """Note 5: the table was computed at exact midband frequencies, not the
    preferred nominal values printed in its own row headings."""
    return 1000.0 * 10.0 ** (k / 10.0)


